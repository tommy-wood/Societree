#!/usr/bin/env node
// Build seed/societree-seed.sql from seed/societree-seed-data.json, so the
// data can be loaded by pasting into the Supabase dashboard's SQL Editor
// (no Node or secret key needed). Same result as scripts/seed.mjs.
//
//   npm run seed:sql

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(await readFile(path.join(root, 'seed', 'societree-seed-data.json'), 'utf8'));

const PRIORITIES = new Set(['low', 'medium', 'urgent']);
const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`; // keeps line breaks
const pr = (p) => (PRIORITIES.has((p ?? '').trim().toLowerCase()) ? q(p.trim().toLowerCase()) : 'null');
const d = (s) => (s && /^\d{4}-\d{2}-\d{2}$/.test(s) ? q(s) : 'null');
const int = (n) => Math.max(0, Math.trunc(Number(n) || 0));

// Same ordering rule as seed.mjs: same-day visits are listed newest first in
// the export, so give earlier rows a later created_at and insert oldest first.
const n = data.visits.length;
const visits = data.visits
  .map((v, i) => ({ ...v, created_at: new Date(Date.parse(`${v.date}T12:00:00Z`) + (n - i) * 1000).toISOString() }))
  .sort((a, b) => a.date.localeCompare(b.date) || a.created_at.localeCompare(b.created_at));

const out = [];
out.push(`-- Societree seed data: ${data.sites.length} sites, ${data.visits.length} visits, ${data.stock_items.length} stock items, ${(data.jobs ?? []).length} jobs.
-- Generated by scripts/make-seed-sql.mjs from seed/societree-seed-data.json. Do not edit by hand.
--
-- HOW TO USE: Supabase dashboard -> SQL Editor -> New query -> paste this whole
-- file -> Run. Run it ONCE, after the database tables exist. It stops without
-- changing anything if there are already sites in the database.

begin;

do $$
begin
  if to_regclass('public.sites') is null then
    raise exception 'The database tables are not set up yet. Apply the migrations first (merge to main with the GitHub integration, or npx supabase db push).';
  end if;
  if exists (select 1 from public.sites) then
    raise exception 'There are already sites in the database, so the seed was not loaded again. Nothing was changed.';
  end if;
end $$;

-- Sites
insert into public.sites (slug, name, address, contact, contact_email, notes, priority) values`);
out.push(
  data.sites
    .map((s) => `  (${q(s.id)}, ${q(String(s.name).trim())}, ${q(s.address)}, ${q(s.contact)}, ${q(s.contact_email)}, ${q(s.notes)}, ${pr(s.priority)})`)
    .join(',\n') + ';',
);

out.push(`\n-- Visits (oldest first; the trigger updates each site's priority and last visit)`);
for (const v of visits) {
  out.push(
    `insert into public.visits (site_id, date, priority_at_visit, work_carried_out, notes, logged_by, legacy_logged_by, legacy_photo_count, created_at)\n` +
      `  select id, ${d(v.date)}, ${pr(v.priority)}, ${q(v.work_carried_out)}, ${q(v.notes)}, null, ${v.logged_by?.trim() ? q(v.logged_by.trim()) : 'null'}, ${int(v.photo_count)}, ${q(v.created_at)}\n` +
      `  from public.sites where slug = ${q(v.site_id)};`,
  );
}

out.push(`\n-- The old app is the source of truth for each site's priority and last visit
-- (e.g. Beaumont park was set to medium by hand although its last visit said low).`);
for (const s of data.sites) {
  out.push(`update public.sites set priority = ${pr(s.priority)}, last_visit = ${d(s.last_visit)} where slug = ${q(s.id)};`);
}

out.push(`\n-- Stock\ninsert into public.stock_items (name, quantity, unit, low_at, kept_at, notes) values`);
out.push(
  data.stock_items
    .map((i) => `  (${q(String(i.name).trim())}, ${int(i.quantity)}, ${q(i.unit)}, ${int(i.low_at)}, ${q(i.kept_at)}, ${q(i.notes)})`)
    .join(',\n') + ';',
);

if (data.jobs?.length) {
  out.push(`\n-- Jobs`);
  for (const j of data.jobs) {
    out.push(`insert into public.jobs (site_id, text, done, created_by) select id, ${q(String(j.text).trim())}, ${j.done ? 'true' : 'false'}, null from public.sites where slug = ${q(j.site_id)};`);
  }
}

out.push(`
commit;

-- Check: should show 22 | 23 | 24 | 4
select (select count(*) from public.sites) as sites,
       (select count(*) from public.visits) as visits,
       (select count(*) from public.stock_items) as stock_items,
       (select count(*) from public.jobs) as jobs;
`);

const file = path.join(root, 'seed', 'societree-seed.sql');
await writeFile(file, out.join('\n'));
console.log(`Wrote ${path.relative(root, file)}`);
