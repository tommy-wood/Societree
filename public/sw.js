// Societree service worker: makes the app installable and quick to open.
// - App code (/_expo/static/..., hashed file names) is cached forever.
// - Pages always try the network first, so a new version shows up straight
//   away; the cached copy is only used when there's no signal.
// - Data from Supabase is never cached here (it's always live).
// Both values are filled in by scripts/postbuild-web.mjs after `expo export`.
const CACHE = 'societree-__BUILD_ID__';
const PRECACHE = /*__PRECACHE__*/ [];
const SHELL = ['/', '/manifest.webmanifest', '/icons/icon-192.png', '/favicon.ico', ...PRECACHE];

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // Supabase, maps, etc.

  if (req.mode === 'navigate') {
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put('/', copy));
          return res;
        })
        .catch(() => caches.match('/')),
    );
    return;
  }

  if (url.pathname.startsWith('/_expo/static/') || url.pathname.startsWith('/icons/') || url.pathname.startsWith('/assets/')) {
    event.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
  }
});
